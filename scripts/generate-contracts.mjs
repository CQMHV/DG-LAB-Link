import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const check = process.argv.includes("--check");
const workspace = fileURLToPath(new URL("../", import.meta.url));
const result = spawnSync("cargo", ["run", "--quiet", "-p", "dg-lab-link-contracts", "--bin", "export-contracts"], {
    cwd: workspace,
    encoding: "utf8",
    windowsHide: true,
    maxBuffer: 8 * 1024 * 1024,
});
if (result.status !== 0) {
    process.stderr.write(result.stderr ?? "Contract export failed\n");
    process.exit(result.status ?? 1);
}
const schemas = JSON.parse(result.stdout);
// Input defaults make request fields optional; serialized snapshots always
// contain them. Keep these distinct instead of conflating their contracts.
function requestDefinitions(schema) {
    const rewrite = (value) => {
        if (Array.isArray(value)) return value.map(rewrite);
        if (value && typeof value === "object") return Object.fromEntries(Object.entries(value).map(([key, child]) => [key,
            key === "$ref" && typeof child === "string" && child.startsWith("#/$defs/") ? child.replace("#/$defs/", "#/$defs/Input") : rewrite(child),
        ]));
        return value;
    };
    const rewritten = rewrite(schema);
    rewritten.$defs = Object.fromEntries(Object.entries(rewritten.$defs ?? {}).map(([name, definition]) => [`Input${name}`, definition]));
    return rewritten;
}
schemas.ControlCommand = requestDefinitions(schemas.ControlCommand);
const definitions = new Map();
for (const schema of Object.values(schemas)) {
    for (const [name, definition] of Object.entries(schema.$defs ?? {})) {
        if (definitions.has(name) && JSON.stringify(definitions.get(name)) !== JSON.stringify(definition)) {
            throw new Error(`Conflicting contract definition: ${name}`);
        }
        definitions.set(name, definition);
    }
}

// The contracts use a deliberately small JSON Schema subset. Fail on new
// structural forms instead of silently generating a weaker type.
function typeOf(schema) {
    if (schema === true || Object.keys(schema).length === 0) return "unknown";
    if (schema === false) return "never";
    if (Object.keys(schema).every((key) => ["default", "title", "description", "examples", "deprecated", "readOnly", "writeOnly"].includes(key))) return "unknown";
    if (schema.$ref) {
        if (!schema.$ref.startsWith("#/$defs/")) throw new Error(`Unsupported reference: ${schema.$ref}`);
        return schema.$ref.slice("#/$defs/".length);
    }
    if ("const" in schema) return JSON.stringify(schema.const);
    if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
    if (schema.oneOf || schema.anyOf) return (schema.oneOf ?? schema.anyOf).map((item) => `(${typeOf(item)})`).join(" | ");
    if (schema.allOf) return schema.allOf.map((item) => `(${typeOf(item)})`).join(" & ");
    if (Array.isArray(schema.type)) return schema.type.map((type) => typeOf({ ...schema, type })).join(" | ");
    switch (schema.type) {
        case "null": return "null";
        case "boolean": return "boolean";
        case "integer": case "number": return "number";
        case "string": return "string";
        case "array":
            if (schema.prefixItems) return `[${schema.prefixItems.map(typeOf).join(", ")}]`;
            return `Array<${typeOf(schema.items ?? true)}>`;
        case "object": {
            const required = new Set(schema.required ?? []);
            const fields = Object.entries(schema.properties ?? {}).map(([name, value]) => `${JSON.stringify(name)}${required.has(name) ? "" : "?"}: ${typeOf(value)};`);
            if (schema.additionalProperties && schema.additionalProperties !== false) fields.push(`[key: string]: ${typeOf(schema.additionalProperties)};`);
            return `{ ${fields.join(" ")} }`;
        }
        default: throw new Error(`Unsupported contract schema: ${JSON.stringify(schema)}`);
    }
}

const output = ["// Generated by npm run generate:contracts. Edit Rust contracts, not this file.", ""];
for (const [name, schema] of [...definitions, ...Object.entries(schemas)].sort(([a], [b]) => a.localeCompare(b))) {
    output.push(`export type ${name} = ${typeOf(schema)};`, "");
}
output.push("export type CommandName = ControlCommand[\"command\"];", "export type CommandParams<N extends CommandName> = Extract<ControlCommand, { command: N }> extends { params: infer P } ? P : Record<string, never>;", "");
const text = output.join("\n");
const destination = fileURLToPath(new URL("../src/lib/generated/contracts.ts", import.meta.url));
if (check) {
    if (readFileSync(destination, "utf8").replaceAll("\r\n", "\n") !== text) {
        console.error("Rust / TypeScript contracts differ. Run npm run generate:contracts.");
        process.exit(1);
    }
} else {
    writeFileSync(destination, text);
}
